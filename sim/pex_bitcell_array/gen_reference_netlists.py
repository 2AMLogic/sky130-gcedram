#!/usr/bin/env python3
"""Generate the study-local schematic-leg reference netlists (issue #383).

Two files, both regenerated mechanically from named committed sources
(never hand-transcribed), both keeping their provenance in the header:

* ``reference/gain_cell_2t_schematic.spice`` -- the bitcell schematic leg:
  the two SKY130 X-device cards (and their continuations) of
  ``design/gain_cell_2t.spice`` wrapped in an active
  ``.SUBCKT gain_cell_2t_layout_0 GND bl rbl rwl sn wl`` / ``.ENDS`` whose
  name and ORDERED pin list are the committed extraction's own header
  (``layout/gain_cell_2t.extract.parasitics.spice``), so the schematic leg
  presents exactly the interface the fresh PDK-bound extraction will. The
  source's commented-out wrapper and its top-level terminator are omitted;
  the device cards themselves are byte-for-byte.

* ``reference/gain_cell_2t_array_4x4_schematic.spice`` -- the array
  schematic leg: all 32 drain/gate/source/body tuples of
  ``layout/gain_cell_2t_array.lvs_reference.spice`` (there is no array
  schematic in ``design/``), each instantiated as the source bitcell's
  matching WR/RD SKY130 X card including its schematic geometry. The LVS
  cards express L/W as ``0.15U/0.42U``; the SKY130 subcircuit expects bare
  micrometres, so the generator takes ``L=0.15 W=0.42`` from the source
  card (numerically cross-checked against the LVS card) -- the extracted
  leg keeps its own extracted junction geometry (AS/AD/PS/PD), which is
  the point of the comparison. Wrapped in the 33-pin
  ``.SUBCKT gain_cell_2t_array_4x4_layout_0`` ordered header of the
  committed array extraction: GND, bl_0..3, rbl_0..3, rwl_0..3, the 16
  sn_r_c in row-major order, wl_0..3.

Stdlib only. ``test_pex_bitcell_array.py`` fails if the committed files
are stale relative to a regeneration.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

STUDY_DIR = Path(__file__).resolve().parent
SIM_DIR = STUDY_DIR.parent
REPO_ROOT = SIM_DIR.parent

sys.path.insert(0, str(SIM_DIR))
sys.path.insert(0, str(STUDY_DIR))
from _evidence_common import parse_cards, sha256_prefixed, spice_number  # noqa: E402

import pex_bench  # noqa: E402

DESIGN = REPO_ROOT / "design" / "gain_cell_2t.spice"
LVS_REFERENCE = REPO_ROOT / "layout" / "gain_cell_2t_array.lvs_reference.spice"

LVS_CARD_RE = re.compile(
    r"^M_(WR|RD)_(\d)_(\d)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+nfet\s+L=(\S+)\s+W=(\S+)\s*$"
)


class GenError(ValueError):
    pass


def bitcell_reference() -> str:
    """Wrap design/gain_cell_2t.spice's two X cards in the extraction's
    ordered header. Only the device cards and their continuations are
    carried; comments, the source's own (commented) wrapper, `.GLOBAL GND`
    and the top-level `.end` are not (the bench binds the GND formal to
    SPICE node 0 itself)."""
    cards = []
    for line in DESIGN.read_text().splitlines():
        s = line.strip()
        if s.upper().startswith(("XM_WR", "XM_RD")) or (s.startswith("+") and cards):
            cards.append(line.rstrip())
    if len([c for c in cards if not c.lstrip().startswith("+")]) != 2:
        raise GenError(f"{DESIGN}: expected exactly XM_WR and XM_RD cards, got {cards!r}")
    pins = pex_bench.CELLS["bitcell"]["pins"]
    top = pex_bench.CELLS["bitcell"]["top"]
    return "\n".join(
        [
            f"* {pex_bench.CELLS['bitcell']['reference'].name} -- bitcell schematic leg for the klt pex",
            "* retention comparison (issue #383). GENERATED by gen_reference_netlists.py; do not edit.",
            f"* The two SKY130 device cards are design/gain_cell_2t.spice verbatim",
            f"* ({sha256_prefixed(DESIGN)}); the active wrapper's name and ORDERED pin list are the",
            f"* committed extraction's own header ({pex_bench.CELLS['bitcell']['committed_extract'].name}).",
            f"* The source's commented wrapper and top-level terminator are omitted.",
            f".SUBCKT {top} {' '.join(pins)}",
            *cards,
            f".ENDS {top}",
            "",
        ]
    )


def _source_geometry() -> dict[str, str]:
    """The source bitcell's trailing parameter text per role (WR/RD),
    taken from the XM_WR / XM_RD cards of design/gain_cell_2t.spice."""
    cards = parse_cards(DESIGN)
    out = {}
    for role in ("WR", "RD"):
        try:
            _nets, model, params = cards[f"M_{role}"]
        except KeyError as exc:
            raise GenError(f"{DESIGN}: no XM_{role} card") from exc
        if model != pex_bench.NFET_MODEL:
            raise GenError(f"{DESIGN}: XM_{role} instantiates {model!r}, expected {pex_bench.NFET_MODEL}")
        out[role] = params
    return out


def _source_lw(params: str) -> tuple[float, float]:
    def val(key: str) -> float:
        m = re.search(rf"\b{key}=(\S+)", params)
        if not m:
            raise GenError(f"geometry params missing {key}=: {params!r}")
        return spice_number(m.group(1))

    return val("L"), val("W")


def array_reference() -> str:
    """The 32-tuple array schematic leg (see module docstring)."""
    geom = _source_geometry()
    lw = {role: _source_lw(params) for role, params in geom.items()}
    cards = []
    seen = set()
    for line in LVS_REFERENCE.read_text().splitlines():
        m = LVS_CARD_RE.match(line.strip())
        if not m:
            continue
        role, r, c, d, g, s, b, l_u, w_u = m.groups()
        r, c = int(r), int(c)
        seen.add((role, r, c))
        if b != "GND":
            raise GenError(f"LVS card body net {b!r} != GND: {line!r}")
        want = (
            (f"sn_{r}_{c}", f"wl_{r}", f"bl_{c}")
            if role == "WR"
            else (f"rbl_{c}", f"sn_{r}_{c}", f"rwl_{r}")
        )
        if (d, g, s) != want:
            raise GenError(f"LVS card tuples {(d, g, s)} != expected {want}: {line!r}")
        lvs_lw = (spice_number(l_u.rstrip("Uu")), spice_number(w_u.rstrip("Uu")))
        if lvs_lw != lw[role]:
            raise GenError(f"LVS card L/W {lvs_lw} != source card {lw[role]}: {line!r}")
        cards.append(
            f"X_{role}_{r}_{c} {d} {g} {s} {b} {pex_bench.NFET_MODEL} {geom[role]}"
        )
    expected = {
        (role, r, c) for role in ("WR", "RD") for r in range(4) for c in range(4)
    }
    if seen != expected:
        raise GenError(f"LVS tuples incomplete: missing {sorted(expected - seen)}, extra {sorted(seen - expected)}")
    pins = pex_bench.CELLS["array"]["pins"]
    top = pex_bench.CELLS["array"]["top"]
    return "\n".join(
        [
            f"* {pex_bench.CELLS['array']['reference'].name} -- 4x4 array schematic leg for the klt pex",
            "* retention comparison (issue #383). GENERATED by gen_reference_netlists.py; do not edit.",
            f"* All 32 D/G/S/B tuples come from {LVS_REFERENCE.name}",
            f"* ({sha256_prefixed(LVS_REFERENCE)}); each is instantiated as the source bitcell's",
            f"* matching WR/RD SKY130 X card with its schematic geometry from design/gain_cell_2t.spice",
            f"* ({sha256_prefixed(DESIGN)}) -- bare-micrometre L/W per the SKY130 subcircuit convention,",
            "* numerically cross-checked against the LVS cards' 0.15U/0.42U. The extracted leg keeps its",
            "* own extracted junction geometry. The wrapper's ORDERED 33-pin header is the committed",
            f"* array extraction's own header ({pex_bench.CELLS['array']['committed_extract'].name}).",
            f".SUBCKT {top} {' '.join(pins)}",
            *cards,
            f".ENDS {top}",
            "",
        ]
    )


def render_all() -> dict[str, str]:
    return {
        str(pex_bench.CELLS["bitcell"]["reference"]): bitcell_reference(),
        str(pex_bench.CELLS["array"]["reference"]): array_reference(),
    }


def main() -> int:
    for path, text in render_all().items():
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        Path(path).write_text(text)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
